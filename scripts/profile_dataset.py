"""
Script to profile the Customer Support on Twitter dataset in memory-efficient chunks.

Usage:
    python scripts/profile_dataset.py --input data/raw/twcs.csv [--chunk-size 100000]
"""

import os
import sys
import argparse
import json
import pandas as pd
from tqdm import tqdm

# Ensure src directory is in Python path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.profiler import inspect_schema, DatasetProfiler


def generate_markdown_report(profile: dict, schema: dict, output_md_path: str):
    """Formats the profile data into a clean, human-readable markdown report."""
    ds = profile["dataset_summary"]
    msg_stats = profile["message_length_stats"]
    conv_stats = profile["conversation_stats"]
    brands = profile["top_brand_candidates"]
    missing = profile["missing_values_by_column"]
    
    md_content = f"""# Dataset Profile Report

## 1. Schema Inspection
- **Columns ({schema['num_columns']})**: `{", ".join(schema['columns'])}`
- **Sample Record**:
```json
{json.dumps(schema['sample_row'], indent=2)}
```

## 2. Dataset Summary
| Metric | Value |
|---|---|
| **Total Messages** | {ds['total_messages']:,} |
| **Inbound (Customer) Messages** | {ds['inbound_messages']:,} ({ds['inbound_messages'] / max(ds['total_messages'], 1):.1%}) |
| **Outbound (Support) Messages** | {ds['outbound_messages']:,} ({ds['outbound_messages'] / max(ds['total_messages'], 1):.1%}) |
| **Unique Authors** | {ds['unique_authors']:,} |
| **Duplicate Tweet IDs** | {ds['duplicate_tweet_ids']:,} |
| **Date Range Start** | {ds['date_range']['start'] or 'N/A'} |
| **Date Range End** | {ds['date_range']['end'] or 'N/A'} |

## 3. Missing Values by Column
| Column | Missing Count | Missing % |
|---|---|---|
"""
    total = max(ds['total_messages'], 1)
    for col, count in missing.items():
        md_content += f"| `{col}` | {count:,} | {count / total:.2%} |\n"

    md_content += f"""
## 4. Message Length Statistics
### Characters
- **Min / Max**: {msg_stats['characters']['min']} / {msg_stats['characters']['max']}
- **Mean**: {msg_stats['characters']['mean']}
- **Median**: {msg_stats['characters']['median']}
- **95th Percentile**: {msg_stats['characters']['p95']}

### Words
- **Min / Max**: {msg_stats['words']['min']} / {msg_stats['words']['max']}
- **Mean**: {msg_stats['words']['mean']}
- **Median**: {msg_stats['words']['median']}
- **95th Percentile**: {msg_stats['words']['p95']}

## 5. Thread / Conversation Statistics
- **Total Reconstructed Conversations**: {conv_stats['total_conversations']:,}
- **Min / Max Conversation Length**: {conv_stats['min_length']} / {conv_stats['max_length']}
- **Mean Conversation Length**: {conv_stats['mean_length']}
- **Median Conversation Length**: {conv_stats['median_length']}

## 6. Top Brand Candidates (Support Accounts)
| Brand / Support ID | Support Messages | Total Conversations | 2-Way Conversations | Avg Thread Length |
|---|---|---|---|---|
"""
    for b in brands:
        md_content += f"| `{b['brand_id']}` | {b['outbound_support_messages']:,} | {b['total_conversations_involved']:,} | {b['two_way_conversations']:,} | {b['avg_conversation_length']} |\n"

    md_content += "\n*Report automatically generated by `scripts/profile_dataset.py`.*\n"

    os.makedirs(os.path.dirname(output_md_path), exist_ok=True)
    with open(output_md_path, "w", encoding="utf-8") as f:
        f.write(md_content)


def main():
    parser = argparse.ArgumentParser(description="Profile Customer Support on Twitter dataset in chunks.")
    parser.add_argument("--input", type=str, default="data/raw/twcs.csv", help="Path to input twcs.csv dataset file.")
    parser.add_argument("--chunk-size", type=int, default=100000, help="Chunk size for streaming CSV processing.")
    args = parser.parse_args()

    input_path = os.path.abspath(args.input)
    if not os.path.exists(input_path):
        print(f"[ERROR] Input file not found at: {input_path}")
        print("Please place twcs.csv in data/raw/ or specify --input path.")
        sys.exit(1)

    print(f"[*] Inspecting schema for: {input_path}")
    schema = inspect_schema(input_path)
    print(f"[+] Found {schema['num_columns']} columns: {schema['columns']}")

    print(f"[*] Processing dataset in chunks of {args.chunk_size:,}...")
    profiler = DatasetProfiler(chunk_size=args.chunk_size)

    # Estimate total rows / chunks if possible
    chunk_reader = pd.read_csv(input_path, chunksize=args.chunk_size, dtype=str)
    for chunk in tqdm(chunk_reader, desc="Processing chunks"):
        profiler.process_chunk(chunk)

    print("[*] Finalizing profile statistics...")
    profile = profiler.finalize_profile()

    # Save JSON report
    reports_dir = os.path.abspath("reports")
    os.makedirs(reports_dir, exist_ok=True)
    json_path = os.path.join(reports_dir, "data_profile.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(profile, f, indent=2)
    print(f"[+] Saved JSON profile to: {json_path}")

    # Save Markdown report
    md_path = os.path.join(reports_dir, "data_profile.md")
    generate_markdown_report(profile, schema, md_path)
    print(f"[+] Saved Markdown report to: {md_path}")


if __name__ == "__main__":
    main()
